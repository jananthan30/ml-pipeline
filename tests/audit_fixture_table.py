def _no_metrics(root):
    (root / "outputs" / "metrics.json").unlink()
    return root


def run_case(root: Path, name: str, builder, args: list[str]) -> dict:
    folder = root / ("case" + str(abs(hash(name)) % 10**8))
    builder(folder)
    _, _, findings = fx.run_audit(folder, *[a.replace("{name}", folder.name) for a in args])
    return findings


def judge_planted(f: dict, code: str, severity, evidence, verdict) -> tuple[bool, str]:
    if code.startswith("could-not-check:"):
        check = next((c for c in f["checks"] if c["id"] == code.split(":", 1)[1]), {})
        got = f"{check.get('id')}: {check.get('status')}"
        ok = check.get("status") == "could not check"
    else:
        hits = [h for h in f["findings"] if h["code"] == code and h["severity"] == severity and h["evidence"] == evidence]
        got = f"{code} {severity}/{evidence}" if hits else "missing (" + ", ".join(
            sorted({f'{h["code"]} {h["severity"]}' for h in f["findings"]})) + ")"
        ok = bool(hits)
    return ok and f["verdict"] == verdict, got


def judge_clean(f: dict, verdict) -> tuple[bool, str]:
    serious = [f"{h['code']} {h['severity']}/{h['evidence']}" for h in f["findings"] if h["severity"] in ("critical", "high")]
    return not serious and f["verdict"] == verdict, ", ".join(serious) or "no critical or high finding"


def main() -> int:
    have = _sklearn()
    wrong = 0
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        print("### Planted problems\n")
        print("| # | Planted problem | Expected finding | Expected verdict | Got | Verdict | Result |")
        print("|---|---|---|---|---|---|---|")
        for i, (name, build, args, code, sev, ev, verdict, needs) in enumerate(PLANTED, 1):
            if needs and not have:
                print(f"| {i} | {name} | {code} | {verdict} | skipped (no scikit-learn) | | SKIP |")
                continue
            f = run_case(root, name, build, args)
            ok, got = judge_planted(f, code, sev, ev, verdict)
            wrong += not ok
            want = code if code.startswith("could-not") else f"{code} {sev}/{ev}"
            print(f"| {i} | {name} | {want} | {verdict} | {got} | {f['verdict']} | {'OK' if ok else 'XX'} |")
        print("\n### Clean controls\n")
        print("| # | Clean control | Expected verdict | Critical/high findings | Verdict | Result |")
        print("|---|---|---|---|---|---|")
        for i, (name, build, args, verdict, needs) in enumerate(CLEAN, 1):
            if needs and not have:
                print(f"| {i} | {name} | {verdict} | skipped (no scikit-learn) | | SKIP |")
                continue
            f = run_case(root, name, build, args)
            ok, got = judge_clean(f, verdict)
            wrong += not ok
            print(f"| {i} | {name} | {verdict} | {got} | {f['verdict']} | {'OK' if ok else 'XX'} |")
    print(f"\n{wrong} of {len(PLANTED) + len(CLEAN)} cases behave wrongly")
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
